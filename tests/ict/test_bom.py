# -*- coding: utf-8 -*-
"""Optional BOM parsing + ComponentLibrary merge tests (headless)."""
from __future__ import annotations

import pytest

from mtkgui.ict.netparse.bom import (
    CATEGORY_DCDC,
    CATEGORY_LDO,
    CATEGORY_MAIN_MCU,
    CATEGORY_OTHER,
    CATEGORY_PMIC,
    BomRecord,
    build_library,
    merge_bom,
    parse_bom,
    split_refdes,
)

HEADER = ("Reference Designator,Name,Number,Description,Quantity\n")


def _csv(tmp_path, body: str, name: str = "bom.csv") -> str:
    path = tmp_path / name
    path.write_text(HEADER + body, encoding="utf-8")
    return str(path)


def test_split_refdes_comma_and_range():
    refs, warnings = split_refdes("C1-C3, R5; U9")
    assert refs == ["C1", "C2", "C3", "R5", "U9"]
    assert warnings == []


def test_split_refdes_dotdot_and_dedup():
    refs, _ = split_refdes("C1..C3 C3")
    assert refs == ["C1", "C2", "C3"]


def test_split_refdes_huge_range_kept_unexpanded():
    refs, warnings = split_refdes("C1-C999")
    assert refs == ["C1-C999"]
    assert warnings and "exceeds" in warnings[0]


def test_parse_bom_real_header_layout(tmp_path):
    path = _csv(tmp_path,
                "U1,750-10117,745000402354,IC MCU S32K566 BGA437,1\n"
                "R1,150-79489,745000013387,CAP CER 10pF 50V,0\n")
    data = parse_bom(path)
    assert [(r.refdes, r.part_number) for r in data.records] == [
        ("U1", "750-10117"), ("R1", "150-79489")]
    assert data.records[0].dnp is False
    assert data.records[1].dnp is True       # Quantity 0


def test_parse_bom_detects_header_after_preamble(tmp_path):
    path = tmp_path / "bom.csv"
    path.write_text(
        "Generated by Innovator\n\n" + HEADER +
        "C1,150-1,745-1,CAP CER 1uF,1\n", encoding="utf-8")
    data = parse_bom(str(path))
    assert len(data.records) == 1
    assert data.records[0].refdes == "C1"


def test_parse_bom_rejects_xls(tmp_path):
    path = tmp_path / "bom.xls"
    path.write_text("x", encoding="utf-8")
    with pytest.raises(ValueError, match=r"unsupported BOM type: \.xls"):
        parse_bom(str(path))


def test_parse_bom_rejects_missing_header(tmp_path):
    path = tmp_path / "bom.csv"
    path.write_text("a,b,c\n1,2,3\n", encoding="utf-8")
    with pytest.raises(ValueError, match="BOM header not found"):
        parse_bom(str(path))


def test_parse_bom_rejects_empty_records(tmp_path):
    path = _csv(tmp_path, "")
    with pytest.raises(ValueError, match="no component records"):
        parse_bom(path)


# --------------------------------------------------------------- merge
def test_merge_overrides_pn_and_recategorizes():
    library = build_library([("U1", "UNKNOWN"), ("R1", "10K")])
    assert library.category_of("U1") == CATEGORY_OTHER
    from mtkgui.ict.netparse.bom import BomData
    report = merge_bom(library, BomData(records=[
        BomRecord("U1", "MIMXRT798S", "IC MCU ARM")]))
    assert library.by_refdes("U1").part_number == "MIMXRT798S"
    assert library.category_of("U1") == CATEGORY_MAIN_MCU
    assert "U1" not in library.unclassified
    assert report.updated == 1
    assert report.conflicts == [("U1", "UNKNOWN", "MIMXRT798S")]


def test_merge_adds_bom_only_devices_at_tail():
    library = build_library([("U1", "MIMXRT798S")])
    from mtkgui.ict.netparse.bom import BomData
    report = merge_bom(library, BomData(records=[
        BomRecord("U2", "PF1500", "IC POWER MANAGEMENT"),
        BomRecord("U3", "TPS62840", "IC VREG DC-DC BUCK CONV")]))
    assert [r.refdes for r in library.records] == ["U1", "U2", "U3"]
    assert library.category_of("U2") == CATEGORY_PMIC
    assert library.category_of("U3") == CATEGORY_DCDC
    assert report.added == 2


def test_merge_description_ldo_and_dnp_or():
    library = build_library([("U1", "UNKNOWN")])
    library.by_refdes("U1").dnp = True
    from mtkgui.ict.netparse.bom import BomData
    report = merge_bom(library, BomData(records=[
        BomRecord("U1", "315-81174", "IC VREG LDO 3.3V")]))
    assert library.category_of("U1") == CATEGORY_LDO
    assert library.by_refdes("U1").dnp is True
    assert report.dnp == 0                    # BOM record itself not DNP


def test_merge_never_drops_schematic_devices():
    library = build_library([("U1", "MIMXRT798S"), ("U9", "KEEPME")])
    from mtkgui.ict.netparse.bom import BomData
    merge_bom(library, BomData(records=[BomRecord("U1", "MIMXRT798S")]))
    assert library.by_refdes("U9") is not None


def test_merge_empty_bom_is_noop():
    library = build_library([("U1", "MIMXRT798S")])
    before = [(r.refdes, r.part_number, r.dev_category)
              for r in library.records]
    from mtkgui.ict.netparse.bom import BomData
    report = merge_bom(library, BomData())
    assert report.records == 0 and report.added == 0
    assert [(r.refdes, r.part_number, r.dev_category)
            for r in library.records] == before


