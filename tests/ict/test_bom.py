def test_parse_bom_explicit_dnp_column_beats_quantity(tmp_path):
    path = tmp_path / "bom.csv"
    path.write_text(
        "RefDes,MPN,DNP,Quantity\n"
        "U1,750-1,Y,1\n"
        "U2,750-2,N,0\n", encoding="utf-8")
    data = parse_bom(str(path))
    assert [(r.refdes, r.dnp) for r in data.records] == [
        ("U1", True), ("U2", False)]


def test_parse_bom_expands_refdes_range(tmp_path):
    path = _csv(tmp_path, "C1-C3,150-1,745-1,CAP CER 1uF,1\n")
    data = parse_bom(path)
    assert [r.refdes for r in data.records] == ["C1", "C2", "C3"]


def test_parse_bom_xlsx(tmp_path):
    openpyxl = pytest.importorskip("openpyxl")
    workbook = openpyxl.Workbook()
    sheet = workbook.active
    sheet.append(["Generated by Innovator"])
    sheet.append(["Reference Designator", "Name", "Number",
                  "Description", "Quantity"])
    sheet.append(["U1", "750-10117", "745000402354", "IC MCU S32K566", 1])
    sheet.append(["C1", "150-79489", "745000013387", "CAP CER 10pF", 0])
    path = tmp_path / "bom.xlsx"
    workbook.save(str(path))
    data = parse_bom(str(path))
    assert [(r.refdes, r.part_number, r.dnp) for r in data.records] == [
        ("U1", "750-10117", False), ("C1", "150-79489", True)]


def test_merge_conflict_only_when_old_pn_exists():
    library = build_library([("U1", "")])
    from mtkgui.ict.netparse.bom import BomData
    report = merge_bom(library, BomData(records=[
        BomRecord("U1", "MIMXRT798S", "IC MCU ARM")]))
    assert report.updated == 1
    assert report.conflicts == []                # nothing to override


def test_merge_duplicate_bom_refdes_last_wins():
    library = build_library([])
    from mtkgui.ict.netparse.bom import BomData
    report = merge_bom(library, BomData(records=[
        BomRecord("U1", "OLD", "", dnp=True),
        BomRecord("U1", "NEW", "IC MCU ARM")]))
    assert library.by_refdes("U1").part_number == "NEW"
    assert library.by_refdes("U1").dnp is True   # OR-merged
    assert report.added == 1 and report.updated == 1
    assert [r.refdes for r in library.records] == ["U1"]


def test_merge_recategorize_to_other_syncs_unclassified():
    library = build_library([("U1", "MIMXRT798S")])
    assert "U1" not in library.unclassified
    from mtkgui.ict.netparse.bom import BomData
    report = merge_bom(library, BomData(records=[
        BomRecord("U1", "150-79489", "CAP CER 10pF 50V")]))
    assert library.category_of("U1") == CATEGORY_OTHER
    assert "U1" in library.unclassified
    assert report.conflicts == [("U1", "MIMXRT798S", "150-79489")]


def test_merge_part_number_beats_description():
    """The ordering code wins over the description fallback."""
    library = build_library([])
    from mtkgui.ict.netparse.bom import BomData
    merge_bom(library, BomData(records=[
        BomRecord("U1", "TPS62840", "IC VREG LDO 3.3V")]))
    assert library.category_of("U1") == CATEGORY_DCDC


def test_merge_report_counts():
    library = build_library([("U1", "OLD"), ("U9", "KEEP")])
    from mtkgui.ict.netparse.bom import BomData
    report = merge_bom(library, BomData(records=[
        BomRecord("U1", "MIMXRT798S", "IC MCU ARM"),
        BomRecord("U2", "PF1500", "IC POWER MANAGEMENT"),
        BomRecord("U3", "TPS62840", "IC VREG DC-DC BUCK", dnp=True)]))
    assert report.records == 3
    assert report.updated == 1
    assert report.added == 2
    assert report.dnp == 1
    assert report.conflicts == [("U1", "OLD", "MIMXRT798S")]
